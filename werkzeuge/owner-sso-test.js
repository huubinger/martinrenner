// Test für owner-sso.js + Login der Tool-Übersicht. Aufruf: node werkzeuge/owner-sso-test.js "$PWD"
const R = process.argv[2];
process.env.TOOLS_PASSWORD = 'testpasswort-123';
process.env.OWNER_SSO_SECRET = 'x'.repeat(40);
const express = require(R + '/node_modules/express');
const sso = require(R + '/owner-sso.js');
const app = express();
app.use(express.urlencoded({ extended: true }));
const readCookie = (req, n) => { for (const p of (req.headers.cookie || '').split(';')) { const i = p.indexOf('='); if (i > 0 && p.slice(0, i).trim() === n) return decodeURIComponent(p.slice(i + 1).trim()); } return null; };
require(R + '/tools-page.js')(app, { readCookie, escapeHtml: (s) => String(s) });
app.all('/probe', (req, res) => { const h = { 'x-owner-sso': 'gefaelscht' }; if (req.headers.cookie) h.cookie = req.headers.cookie; sso.ownerSso(req, h, 'skript'); res.json({ owner: sso.isOwner(req), header: h['x-owner-sso'] || null, cookie: h.cookie || null }); });
const srv = app.listen(0, async () => {
  const base = 'http://localhost:' + srv.address().port;
  const ok = (c, m) => { console.log((c ? 'OK  ' : 'FEHLER ') + m); if (!c) process.exitCode = 1; };
  let r = await fetch(base + '/probe'); let j = await r.json();
  ok(!j.owner && j.header === null, 'ohne Login: kein Owner, gefälschter Header entfernt');
  r = await fetch(base + '/tools/login', { method: 'POST', body: new URLSearchParams({ password: 'falsch', next: '/skript/' }), redirect: 'manual' });
  ok(r.status === 401 && (await r.text()).includes('value="/skript/"'), 'falsches Passwort: 401, next bleibt');
  r = await fetch(base + '/tools/login', { method: 'POST', body: new URLSearchParams({ password: 'testpasswort-123', next: '/skript/' }), redirect: 'manual' });
  const cookies = r.headers.getSetCookie();
  ok(r.status === 303 && r.headers.get('location') === '/skript/', 'Login: Rücksprung zu /skript/');
  const owner = cookies.find((c) => c.startsWith('mr_owner='));
  ok(owner && /Path=\//.test(owner) && /HttpOnly/i.test(owner), 'mr_owner-Cookie für Path=/ und HttpOnly');
  const ck = owner.split(';')[0];
  j = await (await fetch(base + '/probe', { headers: { cookie: ck } })).json();
  ok(j.owner && j.header === sso.toolKey('skript') && j.header.length === 64, 'mit Login: Header = Schlüssel des Tools');
  ok(sso.toolKey('skript') !== sso.toolKey('licht'), 'Schlüssel je Tool verschieden');
  r = await fetch(base + '/tools/login', { method: 'POST', body: new URLSearchParams({ password: 'testpasswort-123', next: '//boese.de' }), redirect: 'manual' });
  ok(r.headers.get('location') === '/tools', 'fremder Rücksprung //boese.de wird verworfen');
  r = await fetch(base + '/tools/login', { method: 'POST', body: new URLSearchParams({ password: 'testpasswort-123', next: '/\\boese.de' }), redirect: 'manual' });
  ok(r.headers.get('location') === '/tools', 'Rücksprung /\\boese.de wird verworfen');
  r = await fetch(base + '/tools', { headers: { cookie: ck } });
  ok(r.status === 200, '/tools mit Owner-Cookie offen');
  r = await fetch(base + '/login?next=/kalender/', { headers: { cookie: ck }, redirect: 'manual' });
  ok(r.status === 303 && r.headers.get('location') === '/kalender/', '/login mit Owner springt direkt weiter');
  r = await fetch(base + '/tools/logout', { headers: { cookie: ck }, redirect: 'manual' });
  ok(r.headers.getSetCookie().some((c) => c.startsWith('mr_owner=;')), 'Abmelden löscht mr_owner');
  j = await (await fetch(base + '/probe', { headers: { cookie: 'mr_owner=' + Date.now() + '.' + 'a'.repeat(64) } })).json();
  ok(!j.owner, 'gefälschtes Cookie: kein Owner');
  j = await (await fetch(base + '/probe', { headers: { cookie: 'a=1; ' + ck + '; tools_auth=x; b=2' } })).json();
  ok(j.cookie === 'a=1; b=2', 'Homepage-Cookies werden nicht an Tools weitergegeben: ' + j.cookie);
  j = await (await fetch(base + '/probe', { method: 'POST', headers: { cookie: ck, 'sec-fetch-site': 'cross-site' } })).json();
  ok(j.owner && j.header === null, 'POST von fremder Seite: kein Owner-Header');
  j = await (await fetch(base + '/probe', { method: 'POST', headers: { cookie: ck, 'sec-fetch-site': 'same-origin' } })).json();
  ok(j.header === sso.toolKey('skript'), 'POST von eigener Seite: Owner-Header');
  const alt = 'mr_owner=' + String(Date.now() - 366 * 864e5) + '.' + ck.split('.')[1];
  j = await (await fetch(base + '/probe', { headers: { cookie: alt } })).json();
  ok(!j.owner, 'Cookie mit anderem/zu altem Zeitstempel ungültig');
  process.env.OWNER_VERSION = '2';
  j = await (await fetch(base + '/probe', { headers: { cookie: ck } })).json();
  ok(!j.owner, 'OWNER_VERSION hochgezählt: alle abgemeldet');
  delete process.env.OWNER_VERSION;
  process.env.OWNER_SSO_SECRET = 'kurz';
  j = await (await fetch(base + '/probe', { headers: { cookie: ck } })).json();
  ok(!j.owner && j.header === null, 'zu kurzes OWNER_SSO_SECRET: gemeinsames Login ganz aus');
  srv.close();
});
